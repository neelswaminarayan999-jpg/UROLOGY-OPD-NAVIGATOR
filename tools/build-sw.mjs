// Regenerates frontend/sw.js: lists every file the app needs and stamps a version hash of their contents.
// Run after changing any frontend file:  node tools/build-sw.mjs   (npm test fails if you forget)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const FRONT = new URL('../frontend/', import.meta.url).pathname;
export function shellFiles() {
  const out = ['/index.html', '/manifest.webmanifest', '/icon.svg'];
  // data/*.json (the weekly shared MCQ bank) is NOT part of the versioned shell: it updates without an app release.
  for (const dir of ['css', 'data', 'app']) for (const f of fs.readdirSync(path.join(FRONT, dir)).sort()) if (/\.(js|css)$/.test(f)) out.push(`/${dir}/${f}`);
  return out;
}
export function buildSw() {
  const files = shellFiles();
  const h = crypto.createHash('sha256');
  for (const f of [...files, '/book-figures.json']) h.update(f).update(fs.readFileSync(path.join(FRONT, f)));
  const version = h.digest('hex').slice(0, 12);
  return `/* Urology Oracle offline worker. GENERATED by tools/build-sw.mjs — do not edit by hand. */
const VERSION = '${version}';
const SHELL = 'oracle-shell-' + VERSION;
const FIGS = 'oracle-figures-' + VERSION;
const DATA = 'oracle-data'; // weekly shared MCQ bank: kept across app versions
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', event => {
  // Download the whole app once, so every page, engine and calculator works without signal.
  event.waitUntil(caches.open(SHELL).then(c => c.addAll(FILES.map(f => new Request(f, { cache: 'reload' })))));
});

self.addEventListener('activate', event => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== SHELL && k !== FIGS && k !== DATA).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('message', event => { if (event.data === 'SKIP_WAITING') self.skipWaiting(); });

self.addEventListener('fetch', event => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  if (url.pathname.startsWith('/api/') || url.pathname === '/health' || url.pathname === '/sw.js') return; // AI and health always live

  // Pages: answer instantly from the saved copy (no wait for a sleeping server); updates arrive via a new worker.
  if (req.mode === 'navigate') {
    event.respondWith(caches.match('/index.html').then(hit => hit || fetch(req)));
    return;
  }
  // Shared MCQ bank: answer from the saved copy at once, refresh it in the background for next time.
  if (url.pathname.startsWith('/data/') && url.pathname.endsWith('.json')) {
    event.respondWith(caches.open(DATA).then(c => c.match(req, { ignoreSearch: true }).then(hit => {
      const net = fetch(req).then(r => { if (r.ok) c.put(req, r.clone()); return r; }).catch(() => hit);
      if (hit) { event.waitUntil(net.then(() => {}, () => {})); return hit; }
      return net;
    })));
    return;
  }
  // Book figures: saved the first time they are opened.
  if (url.pathname === '/book-figures.json') {
    event.respondWith(caches.open(FIGS).then(c => c.match(req).then(hit => hit || fetch(req).then(r => { if (r.ok) c.put(req, r.clone()); return r; }))));
    return;
  }
  event.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req)));
});
`;
}
if (import.meta.url === `file://${process.argv[1]}`) {
  fs.writeFileSync(path.join(FRONT, 'sw.js'), buildSw());
  console.log('frontend/sw.js written,', shellFiles().length, 'files');
}
